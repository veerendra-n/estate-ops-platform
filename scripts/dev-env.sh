#!/usr/bin/env bash
# Creates .env with random local secrets for the compose stack (Codespaces runs this on create). Never commit
# .env. Keeps an existing .env, so secrets survive a rebuild; delete it to start over.
set -euo pipefail
cd "$(dirname "$0")/.."
if [ -f .env ]; then
  echo ".env exists; keeping it"
  exit 0
fi
rand() { head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 32; }
{
  echo "# Generated by scripts/dev-env.sh for this machine only. Never commit."
  echo "POSTGRES_PASSWORD=$(rand)"
  echo "NEO4J_PASSWORD=$(rand)"
  echo "CONSOLE_TOKEN=$(rand)"
  echo "ALERTS_INTAKE_TOKEN=$(rand)"
  echo "SESSION_SECRET=$(rand)$(rand)"
  for t in CONTOSO FABRIKAM; do
    echo "${t}_INTAKE_TOKEN=$(rand)"
    # Credentials for the customer's systems. Here they reach the simulator, which only checks they are set.
    echo "${t}_VCENTER_USER=svc-estate-ops@vsphere.local"
    echo "${t}_VCENTER_PASSWORD=$(rand)"
    echo "${t}_VEEAM_USER=svc-estate-ops"
    echo "${t}_VEEAM_PASSWORD=$(rand)"
    echo "${t}_GRAPH_SECRET=$(rand)"
    echo "${t}_FLEET_TOKEN=$(rand)"
    echo "${t}_EDGE_TOKEN=$(rand)"
  done
  echo
  echo "# Optional: a Claude API key (or set it as a Codespaces secret named ANTHROPIC_API_KEY). Without one the"
  echo "# investigator uses the deterministic graph walk and the copilot is off."
  echo "# ANTHROPIC_API_KEY="
  echo "# Faster demo loops: alerts settle for this many seconds before the investigator starts."
  echo "SETTLE_SECONDS=45"
  echo "DISCOVERY_INTERVAL_MINUTES=5"
  echo "POLL_INTERVAL_MINUTES=0.5"
} > .env
chmod 600 .env
echo "wrote .env (cockpit sign-in token: CONSOLE_TOKEN in .env)"
